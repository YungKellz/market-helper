/// Класс товара определяет, по какому сценарию писать карточку. Косметика и
/// парфюмерия продаются иначе, чем б/у техника: там ключевое — состояние и
/// дефекты, здесь — аромат, оригинальность и свежесть. Один усреднённый промпт
/// на обе задачи выдаёт для парфюма пресную «комиссионку», поэтому сценарий
/// выбирается по распознанной категории.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProductClass {
    /// Парфюмерия и уходовая косметика: мисты, лосьоны, кремы, духи, гели.
    Beauty,
    /// Всё остальное — техника, одежда, мебель, детские товары и т. д.
    Generic,
}

impl ProductClass {
    /// Грубая, но дешёвая классификация по тексту распознанных полей. Ошибка
    /// в сторону Generic безопаснее: там нет чувственных описаний аромата,
    /// которые для не-парфюма звучали бы нелепо.
    pub fn classify(parts: &[&str]) -> ProductClass {
        let hay = parts.join(" ").to_lowercase();
        const BEAUTY: [&str; 26] = [
            "красота", "парфюм", "косметик", "victoria", "виктория сикрет",
            "духи", "туалетная вода", "одеколон", "eau de", " edp", " edt",
            "мист", "mist", "лосьон", "молочко для тела", "крем для тела",
            "крем для рук", "гель для душа", "скраб", "бальзам для тела",
            "масло для тела", "спрей для тела", "сыворотк", "тонер",
            "спрей для волос", "аромат для тела",
        ];
        if BEAUTY.iter().any(|kw| hay.contains(kw)) {
            ProductClass::Beauty
        } else {
            ProductClass::Generic
        }
    }
}

