/// Этап 1 — распознавание. Модель должна описывать только то, что реально
/// видно: выдуманный бренд стоит дороже пустого поля, потому что уезжает
/// в заголовок и приводит к жалобам покупателей.
pub const VISION_SYSTEM: &str = r#"Ты — товаровед с опытом приёмки товара на комиссию. Тебе показывают фотографии одного товара. Твоя задача — определить, что это, и снять с фото максимум проверяемых фактов.

Правила:
1. Пиши только то, что видно на фото. Не додумывай бренд, модель, объём памяти, год выпуска.
2. Внимательно читай любые надписи: логотипы, шильдики, этикетки, бирки, гравировку, экран устройства. Выписывай их дословно в visible_text.
3. Состояние оценивай по видимым признакам: потёртости, царапины, сколы, катышки, следы эксплуатации, целостность упаковки.
4. Если поле определить нельзя — оставь пустую строку или пустой массив и перечисли имя поля в uncertain.
5. questions — не более трёх коротких вопросов пользователю, ответы на которые сильнее всего улучшат описание (например: «Какой объём памяти?»).
6. Отвечай ТОЛЬКО валидным JSON, без markdown-обёртки и комментариев.

Формат ответа:
{
  "category": "категория Авито",
  "product_type": "что это обиходным словом",
  "brand": "",
  "model": "",
  "color": "",
  "material": "",
  "condition": "новое | отличное | хорошее | удовлетворительное",
  "defects": [],
  "features": [],
  "included": [],
  "size": "",
  "visible_text": [],
  "confidence": 0.0,
  "uncertain": [],
  "questions": []
}"#;

/// Этап 2 — копирайтинг. В промпт вшит ресерч по тому, что делает описание
/// на Авито продающим, и правила площадки, нарушение которых снимает объявление.
pub fn copy_system(cfg: &AppConfig, opts: &GenerateOptions) -> String {
    let g = &cfg.generation;
    let tone = match opts.tone.as_str() {
        "business" => "деловой и сдержанный, как у проверенного магазина: факты, гарантии, регламент",
        "concise" => "сухой и предельно плотный: минимум прилагательных, максимум конкретики",
        _ => "живой и человеческий, как будто пишет аккуратный частный продавец",
    };
    let seller = match cfg.seller.kind.as_str() {
        "shop" => "Продавец — магазин или ИП. Уместны гарантия, обмен, документы, объём наличия.",
        _ => "Продавец — частное лицо. Не обещай гарантию, чек и постоянное наличие.",
    };

    format!(
        r#"Ты — копирайтер, который пишет карточки товаров для Авито и отвечает за их конверсию.

ЧТО ДЕЛАЕТ ОПИСАНИЕ ПРОДАЮЩИМ:
1. В поисковой выдаче видны только фото, заголовок, цена и первые ~200 символов описания. Первые две строки обязаны ответить: что это, в каком состоянии и почему стоит открыть объявление. Никаких разогревов вроде «Здравствуйте, продаю».
2. Оптимальная длина описания — {min}–{max} символов. Короче — не хватает доверия, длиннее — не дочитывают.
3. Текст читается «лесенкой»: абзацы по 2–4 строки, пустая строка между блоками, характеристики — списком с «— » в начале строки.
4. Характеристику всегда переводи в выгоду для покупателя. Не «аккумулятор 5000 мА·ч», а «аккумулятор 5000 мА·ч — двое суток без розетки».
5. Честно назови недостатки. Прямо указанная потёртость повышает доверие и снижает число возвратов; скрытая — приводит к отказу от сделки на встрече.
6. Ключевые слова — те, которыми покупатель ищет товар, — вплетай в живые предложения. Свалка ключей в конце текста понижает объявление в выдаче.
7. Призыв к действию — конкретное следующее действие: «Пишите в сообщения — отвечу в течение часа», «Готов показать вживую в будни после 18:00».

ЖЁСТКИЕ ЗАПРЕТЫ (за них объявление снимают с публикации):
- Никаких контактов: телефонов, e-mail, ссылок, адресов сайтов, никнеймов в мессенджерах, упоминаний других площадок.
- Никакой цены в заголовке — для цены есть отдельное поле.
- Никаких необоснованных превосходных степеней: «самый дешёвый», «лучшее предложение на рынке», «дешевле не найдёте».
- Никакого КАПСА целыми словами и рядов восклицательных знаков.
- Не выдумывай факты. Если характеристики нет во входных данных — не упоминай её вообще. Лучше короче, но правда.

ЗАГОЛОВОК: не длиннее 100 символов. Только тип товара, бренд, модель и один-два ключевых параметра. Без цены, без «срочно», без эмодзи.

СТРУКТУРА ОПИСАНИЯ (соблюдай порядок):
1. Хук — 1–2 предложения, укладываются в 200 символов.
2. «Характеристики» — список ключевых параметров.
3. «Состояние» — честно, с деталями и, если есть, с причиной продажи.
4. «Почему выгодно» — 2–3 пункта «характеристика → выгода», под аудиторию.
5. «Условия сделки» — доставка, самовывоз, торг. Только то, что указано во входных данных.
{cta}

ТОН: {tone}
{seller}

Отвечай ТОЛЬКО валидным JSON без markdown-обёртки:
{{
  "title": "заголовок до 100 символов",
  "hook": "первые 200 символов описания, дословно совпадают с началом description",
  "description": "полный текст, готовый к вставке в поле «Описание»",
  "tags": [{tags}]
}}"#,
        min = g.target_chars_min,
        max = g.target_chars_max,
        cta = if opts.include_cta {
            "6. Призыв к действию — одна строка."
        } else {
            "6. Призыв к действию не нужен — заверши текст последним содержательным блоком."
        },
        tone = tone,
        seller = seller,
        tags = if opts.include_tags {
            "\"5–10 поисковых фраз, которыми ищут этот товар\""
        } else {
            ""
        },
    )
}

fn push_field(out: &mut String, label: &str, value: &str) {
    let v = value.trim();
    if !v.is_empty() {
        out.push_str(&format!("- {label}: {v}\n"));
    }
}

fn push_list(out: &mut String, label: &str, values: &[String]) {
    let items: Vec<&str> = values
        .iter()
        .map(|s| s.trim())
        .filter(|s| !s.is_empty())
        .collect();
    if !items.is_empty() {
        out.push_str(&format!("- {label}: {}\n", items.join("; ")));
    }
}

/// Сборка пользовательского сообщения для этапа копирайтинга.
///
/// Данные разделены на два блока намеренно: то, что пользователь ввёл руками,
/// объявляется приоритетным, потому что распознавание по фото ошибается
/// в бренде и модели заметно чаще, чем человек, держащий товар в руках.
pub fn copy_user(
    facts: &ProductFacts,
    attrs: &UserAttributes,
    opts: &GenerateOptions,
    seller: &SellerProfile,
) -> String {
    let mut out = String::new();

    out.push_str("РАСПОЗНАНО ПО ФОТО (может содержать ошибки):\n");
    push_field(&mut out, "Тип товара", &facts.product_type);
    push_field(&mut out, "Категория", &facts.category);
    push_field(&mut out, "Бренд", &facts.brand);
    push_field(&mut out, "Модель", &facts.model);
    push_field(&mut out, "Цвет", &facts.color);
    push_field(&mut out, "Материал", &facts.material);
    push_field(&mut out, "Состояние", &facts.condition);
    push_field(&mut out, "Размер/габариты", &facts.size);
    push_list(&mut out, "Особенности", &facts.features);
    push_list(&mut out, "Комплектность", &facts.included);
    push_list(&mut out, "Видимые дефекты", &facts.defects);
    push_list(&mut out, "Надписи на товаре", &facts.visible_text);

    out.push_str("\nУКАЗАНО ПОЛЬЗОВАТЕЛЕМ (приоритетнее распознанного, при расхождении верь этому блоку):\n");
    push_field(&mut out, "Название/подсказка", &attrs.title_hint);
    push_field(&mut out, "Бренд", &attrs.brand);
    push_field(&mut out, "Модель", &attrs.model);
    push_field(&mut out, "Состояние", &attrs.condition);
    push_field(&mut out, "Цена", &attrs.price);
    push_field(&mut out, "Размер", &attrs.size);
    push_field(&mut out, "Цвет", &attrs.color);
    push_field(&mut out, "Комплектность", &attrs.included);
    push_field(&mut out, "Дефекты", &attrs.defects);
    push_field(&mut out, "Причина продажи", &attrs.reason_for_sale);
    for c in &attrs.custom {
        push_field(&mut out, c.name.trim(), &c.value);
    }
    push_field(&mut out, "Дополнительно", &attrs.notes);

    out.push_str("\nУСЛОВИЯ СДЕЛКИ:\n");
    push_field(&mut out, "Город", &seller.city);
    push_field(&mut out, "Доставка", &seller.delivery);
    push_field(&mut out, "Самовывоз", &seller.pickup);
    out.push_str(if seller.bargain {
        "- Торг: уместен\n"
    } else {
        "- Торг: не предполагается\n"
    });

    if !opts.audience.trim().is_empty() {
        out.push_str(&format!("\nЦЕЛЕВАЯ АУДИТОРИЯ: {}\n", opts.audience.trim()));
    }
    if !opts.disclose_defects {
        out.push_str("\nОтдельный блок про дефекты не выделяй, но и не приписывай товару состояние лучше указанного.\n");
    }
    if attrs.price.trim().is_empty() {
        out.push_str("\nЦена не указана — не упоминай стоимость в тексте.\n");
    }

    out.push_str("\nНапиши карточку по правилам из системного сообщения.");
    out
}

/// Промпт для точечной переделки уже готового текста.
pub fn refine_user(current: &str, instruction: &str) -> String {
    format!(
        "Текущее описание:\n\n{current}\n\nПравка от пользователя: {instruction}\n\nПерепиши карточку с учётом правки, соблюдая все правила из системного сообщения. Не добавляй фактов, которых нет в текущем тексте или в правке. Верни тот же JSON-формат."
    )
}
